from pathlib import Path
import argparse
root = Path(__file__).resolve().parent
parser=argparse.ArgumentParser()
parser.add_argument('--first-node',type=int,default=1)
parser.add_argument('--nodes',type=int,default=2)
args=parser.parse_args()
if args.first_node<1 or args.nodes<1 or args.first_node+args.nodes-1>16:
    parser.error('node range must be within 1..16')
names = ['igw_protocol.h', 'igw_rw_protocol.h', 'igw_can_rw_protocol.h', 'igw_nodes.h', 'igw_driver.h',
         'igw_udp_packet.h', 'can_common.inc', 'rtu_common.inc', 'slave.inc', 'main.inc']
parts = ['/* Generated by generate_slave.py; edit slave_src then regenerate. */\n#define IGW_CAN_MASTER 0\n']
parts.append('#define IGW_FIRST_NODE %d\n#define IGW_NODE_COUNT %d\n'%(args.first_node,args.nodes))
for name in names:
    text = (root/'slave_src'/name).read_text()
    for header in ['igw_protocol.h','igw_rw_protocol.h','igw_can_rw_protocol.h','igw_nodes.h','igw_driver.h']:
        text = text.replace('#include "'+header+'"', '')
    parts.append('/* '+name+' */\n'+text)
(root/'slave/main.c').write_text('\n'.join(parts))
