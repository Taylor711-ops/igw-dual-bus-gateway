from pathlib import Path
root = Path(__file__).resolve().parent
names = ['igw_protocol.h', 'igw_rw_protocol.h', 'igw_can_rw_protocol.h', 'igw_driver.h',
         'igw_udp_packet.h', 'can_common.inc', 'rtu_common.inc', 'slave.inc', 'main.inc']
parts = ['/* Generated by generate_slave.py; edit slave_src then regenerate. */\n#define IGW_CAN_MASTER 0\n']
for name in names:
    text = (root/'slave_src'/name).read_text()
    for header in ['igw_protocol.h','igw_rw_protocol.h','igw_can_rw_protocol.h','igw_driver.h']:
        text = text.replace('#include "'+header+'"', '')
    parts.append('/* '+name+' */\n'+text)
(root/'slave/main.c').write_text('\n'.join(parts))
