#!/usr/bin/env python3
from pathlib import Path
import json
root=Path(__file__).resolve().parent.parent
data=(root/'04_web/monitor/index.html').read_bytes()
header='/* Generated by generate_web.py. */\nstatic const unsigned char web_html[]={\n'
header+='\n'.join(','.join(str(x) for x in data[i:i+24])+',' for i in range(0,len(data),24))
header+='\n};\nstatic const unsigned long web_html_len=sizeof web_html;\n'
(root/'01_gateway_host/PS/monitor/src/web_assets.h').write_text(header,encoding='utf-8')
page=(root/'04_web/file_transfer/file_page.html').read_text(encoding='utf-8')
header='/* Generated from file_page.html. */\nstatic const char FILE_PAGE[] = '+json.dumps(page,ensure_ascii=False)+';\n'
(root/'01_gateway_host/PS/file_transfer/src/file_page.h').write_text(header,encoding='utf-8')
print('WEB_HEADERS_GENERATED')
